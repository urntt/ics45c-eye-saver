/**
 * Builds vendor/highlight.js: highlight.js core plus the grammars the
 * converter can detect, as one classic script for the content-script list.
 *
 * Manifest V3 forbids loading remote code, so the bundle is generated here
 * from the npm package and committed. Rerun after upgrading highlight.js or
 * changing the language set (keep it in sync with detectCodeLanguage in
 * src/converter.js).
 *
 * Usage: npm run build:highlight
 */
import { copyFile, readFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const LANGUAGES = ["cpp", "bash", "makefile"];

const { version } = JSON.parse(await readFile(path.join(ROOT, "node_modules/highlight.js/package.json"), "utf8"));

const entry = `
import hljs from "highlight.js/lib/core";
${LANGUAGES.map((name) => `import ${name} from "highlight.js/lib/languages/${name}";`).join("\n")}
${LANGUAGES.map((name) => `hljs.registerLanguage("${name}", ${name});`).join("\n")}

/** Returns highlighted HTML (input is escaped by highlight.js). */
export function highlight(code, language) {
  return hljs.highlight(code, { language, ignoreIllegals: true }).value;
}
`;

await build({
  stdin: { contents: entry, resolveDir: ROOT, loader: "js" },
  bundle: true,
  minify: true,
  format: "iife",
  globalName: "Ics45cHighlight",
  legalComments: "inline",
  banner: {
    js: `/* Generated by scripts/build-highlight.mjs from highlight.js ${version} (${LANGUAGES.join(", ")}). Do not edit. BSD-3-Clause, see highlight.js.LICENSE. */`,
  },
  outfile: path.join(ROOT, "vendor/highlight.js"),
});
await copyFile(path.join(ROOT, "node_modules/highlight.js/LICENSE"), path.join(ROOT, "vendor/highlight.js.LICENSE"));
console.log(`vendor/highlight.js built from highlight.js ${version}`);
